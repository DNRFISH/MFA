#help file for merging branches

#need to follow this process in order to merge and then delete local branch

#1: Commit and push changes from local machine
#2: Go to Github (website)
#3: Open Pull Request
#4: Merge into main; use "merge and squash"
#5: Delete branch (on GitHub); note that this resolves any linked issues!
#6: Go back to R Studio to clean locally
#7: Switch to main branch (git checkout main)
#8: Pull updates (git pull)
#9: Remove remote trackin references (git fetch -p)
#10: Delete local branch (git branch -d [branch name]); if error, captial D forces delete; make sure main is updated!!
#11: Refresh using git button or restart R studio

